/**
 * 环面世界边长（格）。东西、南北各绕一圈都是这个数。
 *
 * ⚠️ 这个值必须整除 CHUNK 与 REGION，否则最后一列块/区域只有半格宽，
 * 而「回绕后必然一致」这条性质依赖于区域网格本身也在环面上闭合。
 * 512 = 16×32 = 16×32，两者都整除。
 */
export const WORLD_SIZE = 512

/** 环面最短位移的上界。delta() 的值域是 [-WORLD_HALF, WORLD_HALF) */
export const WORLD_HALF = WORLD_SIZE / 2

/** 渲染分块边长（格）。16×16 = 256 块，一块 1024 个显示格，建网格约 1ms */
export const CHUNK = 32

/** 宏观规划的区域边长（格）。16×16 = 256 个区域，城镇按区域掷点 */
export const REGION = 32

/** 一个游戏日的分钟数 */
export const MINUTES_PER_DAY = 1440

/**
 * 相机俯角（弧度）。62° —— 用户要求 60–70°；
 * 地表格投影成 1 × sin62° = 0.88，接近方形。
 *
 * ⚠️ 偏航恒为 0（轴对齐，不是 45° 等距菱形）。参考图是轴对齐的手绘俯视。
 * 这条性质让 up·forward = 0，精灵深度恒等于脚底深度 —— 整套「精灵零排序」
 * 都建立在它上面，改俯角可以，改偏航会让排序假设失效。
 */
export const PITCH = (62 * Math.PI) / 180

/** 一个世界格在 DPR=1 下占多少屏幕像素 */
export const TILE_PX = 56
